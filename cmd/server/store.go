// cmd/server/store.go
//
// The database layer. This file contains ALL the SQL of the project:
//   - OpenDatabase / seedBooks : open catalog.db, create the table, add samples.
//   - Store                    : one function per query (get, list, create).
//
// The gRPC methods in service.go never write SQL; they call the Store.
// Every Store function receives the RPC's context (ctx). The context carries the
// client's deadline and cancellation, and the *Context database calls
// (QueryRowContext, ExecContext, ...) stop working when the context ends.
package main

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"strings"

	// Underscore import: load go-sqlite3 only for its side effect. It registers
	// a driver named "sqlite3" in database/sql, which sql.Open uses below.
	// (This driver uses CGO, so a C compiler such as gcc must be installed.)
	_ "github.com/mattn/go-sqlite3"

	// The code generated by protoc. We import it as "pb". Book is a protobuf
	// message type, and the Store returns it directly so that the service does
	// not need to convert between two different "book" structs.
	pb "book-catalog-grpc/gen/catalogpb"
)

// Our own errors. The Store returns these; service.go translates them into
// gRPC status codes (NotFound, AlreadyExists). Keeping them separate means the
// Store knows nothing about gRPC.
var (
	ErrNotFound      = errors.New("book not found")
	ErrDuplicateISBN = errors.New("duplicate isbn")
)

// createBooksTable is the schema. Constraints are rules that SQLite itself
// enforces, even if the Go validation had a bug:
//   - PRIMARY KEY AUTOINCREMENT: SQLite generates the id.
//   - NOT NULL:                  the column must have a value.
//   - UNIQUE:                    no two books may share an isbn.
//   - CHECK (price > 0), CHECK (stock >= 0): value ranges.
const createBooksTable = `
CREATE TABLE IF NOT EXISTS books (
	id     INTEGER PRIMARY KEY AUTOINCREMENT,
	title  TEXT    NOT NULL,
	author TEXT    NOT NULL,
	isbn   TEXT    NOT NULL UNIQUE,
	price  REAL    NOT NULL CHECK (price > 0),
	stock  INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);`

// OpenDatabase opens (and creates, if missing) the SQLite file at `path`,
// creates the books table if needed and seeds sample books if the table is empty.
//
// Called once by main() with "catalog.db", and by every test with a temporary
// file. It never deletes or resets existing data, so restarting the server
// keeps all books.
func OpenDatabase(path string) (*sql.DB, error) {
	// sql.Open does not connect yet; it only prepares a pool of connections.
	db, err := sql.Open("sqlite3", path)
	if err != nil {
		return nil, fmt.Errorf("open database: %w", err)
	}

	// SQLite allows one writer at a time. A single connection makes concurrent
	// RPCs wait for each other instead of failing with "database is locked".
	db.SetMaxOpenConns(1)

	// This is startup code, not an RPC, so there is no client deadline.
	// context.Background() is an empty context that is never cancelled.
	ctx := context.Background()

	// PingContext makes the first real connection, which creates the file.
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, fmt.Errorf("connect to database: %w", err)
	}
	// "IF NOT EXISTS" makes this safe on every start; an existing table is kept.
	if _, err := db.ExecContext(ctx, createBooksTable); err != nil {
		db.Close()
		return nil, fmt.Errorf("create books table: %w", err)
	}
	if err := seedBooks(ctx, db); err != nil {
		db.Close()
		return nil, fmt.Errorf("insert sample books: %w", err)
	}
	return db, nil
}

// seedBooks inserts three sample books, but ONLY when the table is empty, so
// restarting the server never creates duplicates and never overwrites data.
// Called by OpenDatabase.
func seedBooks(ctx context.Context, db *sql.DB) error {
	// QueryRowContext runs a query that returns one row; Scan copies the column
	// into the Go variable whose address (&count) we pass.
	var count int
	if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM books").Scan(&count); err != nil {
		return err
	}
	if count > 0 {
		return nil // The table already has data: do nothing.
	}

	samples := []struct {
		title  string
		author string
		isbn   string
		price  float64
		stock  int
	}{
		{"The Go Programming Language", "Alan Donovan and Brian Kernighan", "978-0134190440", 39.99, 10},
		{"Learning Go", "Jon Bodner", "978-1492077213", 44.50, 5},
		{"Concurrency in Go", "Katherine Cox-Buday", "978-1491941195", 35.00, 3},
	}
	for _, s := range samples {
		// Each ? is a placeholder. The values are sent to SQLite separately
		// from the SQL text, so they can never be run as SQL code (this is what
		// prevents SQL injection).
		_, err := db.ExecContext(ctx,
			"INSERT INTO books (title, author, isbn, price, stock) VALUES (?, ?, ?, ?, ?)",
			s.title, s.author, s.isbn, s.price, s.stock)
		if err != nil {
			return err
		}
	}
	return nil
}

// Store wraps the database connection pool. The gRPC service owns one Store.
type Store struct {
	DB *sql.DB
}

// isDuplicateISBN reports whether err was caused by the UNIQUE constraint on
// books.isbn. SQLite words it as "UNIQUE constraint failed: books.isbn". We
// look for that exact text so that other database errors are NOT mistaken for
// a duplicate (they stay unexpected errors -> codes.Internal).
func isDuplicateISBN(err error) bool {
	return strings.Contains(err.Error(), "UNIQUE constraint failed: books.isbn")
}

// GetBook returns the book with the given id.
// Called by GetBook and CheckAvailability in service.go (which already checked id > 0).
// Returns ErrNotFound if no row has this id; any other error is unexpected.
func (s *Store) GetBook(ctx context.Context, id int32) (*pb.Book, error) {
	// QueryRowContext is for statements that return at most ONE row.
	row := s.DB.QueryRowContext(ctx,
		"SELECT id, title, author, isbn, price, stock FROM books WHERE id = ?", id)

	// Scan copies the six columns, in order, into the fields of a new Book.
	// pb.Book is a struct generated by protoc; its Go field names are Id, Title,
	// Author, Isbn, Price and Stock. We use a pointer (&pb.Book{}) because
	// protobuf messages must not be copied by value.
	book := &pb.Book{}
	err := row.Scan(&book.Id, &book.Title, &book.Author, &book.Isbn, &book.Price, &book.Stock)
	if errors.Is(err, sql.ErrNoRows) {
		// "No row found" is not a server failure: the client asked for a book
		// that does not exist. We translate it into our own ErrNotFound.
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err // Unexpected database problem.
	}
	return book, nil
}

// ListBooks returns one page of books and the total number of books.
// Called by ListBooks in service.go with page >= 1 and 1 <= pageSize <= 50.
//
// Pages are stable because of ORDER BY id: without an ORDER BY, SQLite may
// return rows in any order, and pages could overlap or skip books.
// A page past the last book is not an error: it returns an empty list.
func (s *Store) ListBooks(ctx context.Context, page, pageSize int32) ([]*pb.Book, int32, error) {
	// First, the total number of rows in the whole table.
	var total int32
	err := s.DB.QueryRowContext(ctx, "SELECT COUNT(*) FROM books").Scan(&total)
	if err != nil {
		return nil, 0, err
	}

	// OFFSET = how many rows to skip. Page 1 skips 0, page 2 skips pageSize, ...
	// We compute it as int64 so a huge page number cannot overflow an int32.
	offset := (int64(page) - 1) * int64(pageSize)

	// QueryContext is for statements that return MANY rows.
	rows, err := s.DB.QueryContext(ctx,
		"SELECT id, title, author, isbn, price, stock FROM books ORDER BY id LIMIT ? OFFSET ?",
		pageSize, offset)
	if err != nil {
		return nil, 0, err
	}
	// Always close rows, otherwise the database connection stays busy.
	defer rows.Close()

	// Start with an empty (not nil) slice so "no books" is an empty list.
	books := []*pb.Book{}
	for rows.Next() {
		book := &pb.Book{}
		err := rows.Scan(&book.Id, &book.Title, &book.Author, &book.Isbn, &book.Price, &book.Stock)
		if err != nil {
			return nil, 0, err
		}
		books = append(books, book)
	}
	// rows.Next() also stops when an error happens; check for it here.
	if err := rows.Err(); err != nil {
		return nil, 0, err
	}
	return books, total, nil
}

// CreateBook inserts a new book and returns it, including the generated id.
// Called by CreateBook in service.go with already validated values.
// Returns ErrDuplicateISBN if another book already has the same isbn.
func (s *Store) CreateBook(ctx context.Context, title, author, isbn string, price float64, stock int32) (*pb.Book, error) {
	// ExecContext is for statements that do not return rows (INSERT/UPDATE/DELETE).
	result, err := s.DB.ExecContext(ctx,
		"INSERT INTO books (title, author, isbn, price, stock) VALUES (?, ?, ?, ?, ?)",
		title, author, isbn, price, stock)
	if err != nil {
		if isDuplicateISBN(err) {
			return nil, ErrDuplicateISBN
		}
		return nil, err
	}

	// LastInsertId is the id that SQLite generated (AUTOINCREMENT) for the new row.
	newID, err := result.LastInsertId()
	if err != nil {
		return nil, err
	}
	// Read the row back so that the response shows exactly what was stored.
	return s.GetBook(ctx, int32(newID))
}
